export type Key = keyof typeof en;

export const ago = (iso: string) => {
  const min = Math.round((Date.now() - Date.parse(iso)) / 60_000);
  if (min < 1) return t("justNow");
  if (min < 60) return t("minutesAgo", { n: min });
  if (min < 24 * 60) return t("hoursAgo", { n: Math.round(min / 60) });
  return new Date(iso).toLocaleDateString("en", { day: "numeric", month: "short" });
};

// How long a guest's canvas lasts, from the server's hours (/api/config): "24 hours", "3 days".
export const lifetime = (hours: number) =>
  hours > 24 && hours % 24 === 0 ? t("nDays", { n: hours / 24 }) : hours === 1 ? t("oneHour") : t("nHours", { n: hours });

export function t(key: Key, vars?: Record<string, string | number>) {
  let s: string = en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
